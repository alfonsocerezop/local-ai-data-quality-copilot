import json
from pathlib import Path

from ollama import chat


PROJECT_ROOT = Path(__file__).resolve().parent.parent

FAILURES_PATH = PROJECT_ROOT / "outputs" / "grounded_failures.json"
OUTPUT_PATH = PROJECT_ROOT / "outputs" / "ai_explanations.json"

MODEL = "gemma3:4b"


TEST_CONTEXT = {
    "not_null": {
        "risk": (
            "A required business identifier or field is missing."
        ),
        "investigation": (
            "Review the affected record and determine whether the missing "
            "value can be reliably recovered from authoritative evidence."
        ),
        "human_decision": (
            "Determine whether the missing value can be reliably recovered. "
            "If it cannot, decide whether the record should be rejected, "
            "quarantined, or accepted under an explicitly approved exception."
        ),
    },
    "unique": {
        "risk": (
            "More than one record uses a value that is expected to be unique."
        ),
        "investigation": (
            "Compare the affected records and determine whether they represent "
            "different valid business events, the same business event, or an "
            "identifier error."
        ),
        "human_decision": (
            "Determine whether the affected records are distinct valid "
            "business events that incorrectly share the same identifier, "
            "or whether one or more records are erroneous."
        ),
    },
    "accepted_values": {
        "risk": (
            "A value exists outside the currently accepted business domain."
        ),
        "investigation": (
            "Determine whether the observed value is a valid business value "
            "that requires a contract update, or whether the record is invalid."
        ),
        "human_decision": (
            "Determine whether the observed value is valid and the accepted "
            "values contract should change, or whether the affected record "
            "contains an invalid value."
        ),
    },
}


def load_failures():
    if not FAILURES_PATH.exists():
        raise FileNotFoundError(
            f"Failure file not found: {FAILURES_PATH}"
        )

    with FAILURES_PATH.open("r", encoding="utf-8") as file:
        return json.load(file)


def enrich_failure(failure):
    test_type = failure.get("test")

    context = TEST_CONTEXT.get(
        test_type,
        {
            "risk": (
                "A deterministic data quality rule has been violated."
            ),
            "investigation": (
                "Review the affected records and the violated rule."
            ),
            "human_decision": (
                "Determine the appropriate remediation based on authoritative "
                "business evidence."
            ),
        },
    )

    enriched = dict(failure)

    enriched["deterministic_context"] = {
        "generic_risk": context["risk"],
        "recommended_investigation": context["investigation"],
        "required_human_decision": context["human_decision"],
    }

    return enriched


def build_prompt(failure):
    enriched_failure = enrich_failure(failure)

    evidence = json.dumps(
        enriched_failure,
        indent=2,
        ensure_ascii=False,
    )

    return f"""
You are a senior enterprise data quality assistant.

Your task is to explain a deterministic data quality failure.

The JSON below is authoritative evidence generated by deterministic controls.

EVIDENCE

{evidence}

STRICT RULES

Use only the evidence provided.

Do not invent or assume:
- source systems
- ETL processes
- ingestion processes
- transformation processes
- applications
- teams
- users
- platforms
- migrations
- business workflows
- data lineage
- operational processes

Do not infer relationships between records.

Do not state that records belong to:
- the same customer
- the same transaction
- the same order
- the same business event

unless the evidence explicitly proves it.

When the evidence identifies only a source file,
refer only to that source file and the affected records.

Clearly separate observed facts from hypotheses.

Never present a hypothesis as a fact.

If the root cause cannot be determined from the evidence,
state exactly:

"Root cause cannot be determined from the available evidence."

Always identify affected records using record_reference
when available.

Do not recommend directly modifying downstream analytical tables.

Do not recommend changing a data contract unless a human
first confirms that the observed value is valid.

For BUSINESS IMPACT:

Describe only the generic consequence of violating the tested
data-quality rule.

Do not introduce domain-specific impacts such as marketing,
finance, fulfillment, reconciliation, customer service, or
inventory unless explicitly present in the evidence.

For RECOMMENDED INVESTIGATION:

Use only:
- the affected records
- the observed values
- the expected rule
- the deterministic test context provided in the evidence

For SUGGESTED ACTION:

Recommend the smallest next action supported by the evidence.

Do not recommend changing production data directly.

For HUMAN DECISION:

Never answer "None".

Use the required_human_decision provided in the deterministic
context as guidance.

Adapt it to the specific affected records and observed values.

Respond using exactly these sections:

OBSERVED EVIDENCE

WHAT FAILED

AFFECTED RECORDS

BUSINESS IMPACT

ROOT CAUSE ASSESSMENT

RECOMMENDED INVESTIGATION

SUGGESTED ACTION

HUMAN DECISION

Be concise, operational, and evidence-based.
"""


def explain_failure(failure):
    response = chat(
        model=MODEL,
        messages=[
            {
                "role": "user",
                "content": build_prompt(failure),
            }
        ],
    )

    return response.message.content


def main():
    failures = load_failures()

    explanations = []

    print(f"Failures to explain: {len(failures)}")

    for failure in failures:
        print(
            f"\nExplaining: "
            f"{failure.get('test')} / {failure.get('column')}"
        )

        explanation = explain_failure(failure)

        explanations.append(
            {
                "failure": failure,
                "ai_explanation": explanation,
            }
        )

        print(explanation)

    with OUTPUT_PATH.open("w", encoding="utf-8") as file:
        json.dump(
            explanations,
            file,
            indent=2,
            ensure_ascii=False,
        )

    print(f"\nOutput written to: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()